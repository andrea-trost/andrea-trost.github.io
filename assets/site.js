(function () {
  'use strict';

  function esc(s) {
    return String(s == null ? '' : s).replace(/[&<>"]/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c];
    });
  }

  /* ---------- spectrum strip ----------
     Loads pre-processed spectra from data/spectra.json (generated by
     make_spectra_json.py).  Falls back to a procedural placeholder if
     the fetch fails (e.g. when opening the file locally without a server). */
  function spectrumFallback(root) {
    var seed = Math.random() * 1000;
    var n = 96;
    var c = 60 + Math.floor(Math.random() * 24);
    function rnd(i, k) {
      var x = Math.sin(i * 12.9898 + seed * 78.233 + k * 37.719) * 43758.5453;
      return x - Math.floor(x);
    }
    root.innerHTML = '';
    for (var i = 0; i < n; i++) {
      var h = 78 + 5 * Math.sin(i * 0.8 + seed);
      if (i < c - 12) {
        if (rnd(i, 1) > 0.55) { h -= 14 + 52 * rnd(i, 2); } else { h -= 6 * rnd(i, 2); }
      }
      h += 34 * Math.exp(-Math.pow((i - c) / 5, 2));
      var bar = document.createElement('div');
      bar.className = 'bar';
      bar.style.height = Math.max(8, Math.round(h)) + 'px';
      root.appendChild(bar);
    }
  }

  function drawSpectrumSVG(root, entry) {
    var wave = entry.wave;
    var flux = entry.flux;
    var N = wave.length;

    var fMin = Infinity, fMax = -Infinity;
    for (var i = 0; i < N; i++) {
      if (flux[i] < fMin) fMin = flux[i];
      if (flux[i] > fMax) fMax = flux[i];
    }
    var fRange = fMax - fMin || 1;

    // Build SVG polyline in a 1000×128 viewBox (stretches to container via preserveAspectRatio)
    var VW = 1000, VH = 128, PAD = 8;
    var pts = [];
    for (var j = 0; j < N; j++) {
      var x = (j / (N - 1)) * VW;
      var y = PAD + (1 - (flux[j] - fMin) / fRange) * (VH - 2 * PAD);
      pts.push(x.toFixed(1) + ',' + y.toFixed(1));
    }

    root.innerHTML =
      '<svg xmlns="http://www.w3.org/2000/svg"' +
      '     viewBox="0 0 ' + VW + ' ' + VH + '"' +
      '     preserveAspectRatio="none"' +
      '     width="100%" height="100%"' +
      '     aria-hidden="true">' +
      '<polyline points="' + pts.join(' ') + '"' +
      '  fill="none"' +
      '  stroke="var(--bright)"' +
      '  stroke-width="1.8"' +
      '  stroke-linejoin="round"' +
      '  vector-effect="non-scaling-stroke"/>' +
      '</svg>';
  }

  function spectrum(root) {
    // Show placeholder immediately while fetch is in flight
    spectrumFallback(root);

    fetch('data/spectra.json')
      .then(function (r) {
        if (!r.ok) throw new Error('status ' + r.status);
        return r.json();
      })
      .then(function (data) {
        if (!data || !data.length) return;
        var entry = data[Math.floor(Math.random() * data.length)];
        drawSpectrumSVG(root, entry);
        // Update caption: "spectrum · J1015-1213 · z = 4.19"
        var cap = root.closest('footer') && root.closest('footer').querySelector('.cap');
        if (cap) {
          cap.textContent = 'spectrum · ' + entry.name + ' · z = ' + entry.z.toFixed(2);
        }
      })
      .catch(function () { /* keep the procedural placeholder */ });
  }

  /* ---------- left menu, selection kept in the URL hash (page.html#name) ---------- */
  function sidebar(navEl, names, prefix, onSelect) {
    function current() {
      var h = decodeURIComponent(location.hash.replace('#', ''));
      return names.indexOf(h) >= 0 ? h : names[0];
    }
    function render() {
      var sel = current();
      navEl.innerHTML = '';
      names.forEach(function (n) {
        var a = document.createElement('a');
        a.href = '#' + n;
        a.textContent = prefix + n;
        a.className = n === sel ? 'side on' : 'side';
        if (n === sel) { a.setAttribute('aria-current', 'true'); }
        navEl.appendChild(a);
      });
      onSelect(sel);
    }
    window.addEventListener('hashchange', render);
    render();
  }

  /* ---------- pages ---------- */
  function research() {
    var data = window.RESEARCH;
    var names = data.map(function (p) { return p.id; });
    var content = document.getElementById('content');
    sidebar(document.getElementById('side'), names, '~/research/', function (sel) {
      var p = data.filter(function (x) { return x.id === sel; })[0];
      var fig = p.image
        ? '<img src="' + esc(p.image) + '" alt="' + esc(p.caption) + '">'
        : p.plot ? '<div class="fig-ph">' + esc(p.plot) + '</div>' : '';
      var more = (p.extra || []).map(function (e) {
        return esc(e.label) + ' · <a href="' + esc(e.href) + '">' + esc(e.text) + '</a>';
      }).join(' · ');
      content.innerHTML =
        '<div class="proj">' +
        '<div class="proj-head"><div class="n">' + esc(p.n) + '</div><h1>## ' + esc(p.title) + '</h1></div>' +
        '<p class="meta">' + esc(p.meta) + '</p>' +
        p.paragraphs.map(function (t) { return '<p class="text">' + esc(t) + '</p>'; }).join('') +
        fig +
        '<p class="cap">' + esc(p.caption) + '</p>' +
        (more ? '<p class="more">' + more + '</p>' : '') +
        '</div>';
    });
  }

  function listPage(names, prefix, rows, rowHtml) {
    var content = document.getElementById('content');
    sidebar(document.getElementById('side'), names, prefix, function (sel) {
      var items = rows(sel);
      content.innerHTML =
        '<div class="list-head"><h1>## ' + esc(sel) + '</h1><div class="count">' +
        items.length + (items.length === 1 ? ' entry' : ' entries') + '</div></div>' +
        items.map(rowHtml).join('');
    });
  }

  function publications() {
    var pubs = window.PUBLICATIONS;
    listPage(window.PUBLICATION_LISTS, '~/publications/', function (sel) {
      return pubs.filter(function (p) { return p.lists.indexOf(sel) >= 0; });
    }, function (p, i) {
      var doi = p.doi ? 'https://doi.org/' + p.doi : '';
      var arx = p.arxiv ? 'https://arxiv.org/abs/' + p.arxiv : '';
      var href = doi || arx || '#';
      return '<div class="entry"><div class="when">[' + (i + 1) + ']</div><div class="body">' +
        '<a class="t" href="' + esc(href) + '">' + esc(p.title) + '</a>' +
        '<div class="m"><div>' + esc(p.authors) + '</div><div>' + esc(p.venue) + ' · ' + esc(p.date) + '</div>' +
        (doi ? '<a href="' + esc(doi) + '">[ doi ]</a>' : '') +
        (arx ? '<a href="' + esc(arx) + '">[ arxiv ]</a>' : '') +
        '</div></div></div>';
    });
  }

  function cv() {
    var data = window.CV;
    listPage(window.CV_SECTIONS, '~/cv/', function (sel) {
      return data[sel] || [];
    }, function (e) {
      return '<div class="entry"><div class="when">' + esc(e.when) + '</div><div class="body">' +
        '<div class="t">' + esc(e.title) + '</div>' +
        (e.where ? '<div class="m">' + esc(e.where) + '</div>' : '') +
        (e.note ? '<div class="m">' + esc(e.note) + '</div>' : '') +
        '</div></div>';
    });
  }

  var strip = document.querySelector('.spectrum');
  if (strip) { spectrum(strip); }

  var page = document.body.getAttribute('data-page');
  if (page === 'research') { research(); }
  if (page === 'publications') { publications(); }
  if (page === 'cv') { cv(); }

  // ── theme toggle ──────────────────────────────────────────────
  (function () {
    var btn = document.getElementById('theme-btn');
    if (!btn) return;
    function apply(theme) {
      document.documentElement.setAttribute('data-theme', theme);
      btn.textContent = theme === 'light' ? '[ dark ]' : '[ light ]';
      try { localStorage.setItem('theme', theme); } catch (e) {}
    }
    // init label from current state
    var cur = document.documentElement.getAttribute('data-theme') || 'dark';
    btn.textContent = cur === 'light' ? '[ dark ]' : '[ light ]';
    btn.addEventListener('click', function () {
      var next = document.documentElement.getAttribute('data-theme') === 'light' ? 'dark' : 'light';
      apply(next);
    });
  })();

})();
